static int cal_stream_rd(int fifo_id_src0,int fifo_id_src1)
{
    int rd;
	int rs1 = (fifo_id_src0 & 0x3) | ((fifo_id_src1 & 0x3) << 2);
    asm volatile (
       ".insn r 0x0b, 7, 0, %0, %1, x0"
             :"=r"(rd) 
             :"r"(rs1)
     );
    return rd; 
}

