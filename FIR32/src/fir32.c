void fir_filter(int *input, volatile int *output, int length) {
    int shift_reg[FILTER_ORDER] = {0};

    /* ========================================================
     * 第一段：预热期（开头）
     * i = 0 ~ FILTER_ORDER-2
     * shift_reg 还没填满，有效系数个数 = i+1
     * ======================================================== */
    for (int i = 0; i < FILTER_ORDER - 1; i++) {

        // 数据流入
        for (int j = FILTER_ORDER - 1; j > 0; j--) {
            shift_reg[j] = shift_reg[j-1];
        }
        shift_reg[0] = input[i];

        // 只累加有效的 i+1 个系数
        output[i] = 0;
        for (int j = 0; j <= i; j++) {
            output[i] += shift_reg[j] * fir_coeffs[j];
        }
    }

    /* ========================================================
     * 第二段：稳态期（中间）
     * i = FILTER_ORDER-1 ~ length-1
     * shift_reg 完全填满，所有 FILTER_ORDER 个系数全部参与
     * ======================================================== 
    
     for (int i = FILTER_ORDER - 1; i < length; i++) {

        // 数据流入
        for (int j = FILTER_ORDER - 1; j > 0; j--) {
            shift_reg[j] = shift_reg[j-1];
        }
        shift_reg[0] = input[i];

        // 全部 FILTER_ORDER 个系数都用到
        output[i] = 0;
        for (int j = 0; j < FILTER_ORDER; j++) {
            output[i] += shift_reg[j] * fir_coeffs[j];
        }
    }
    */

    cfg_i(1,FILTER_ORDER,0);
    cfg_i(1,SIGNAL_LENGTH,1);
    cfg_i_limit(FILTER_ORDER,0); 
    cfg_i_limit(FILTER_ORDER,1); // >=MNK no limit
    cfg_i_offset(0,0);
    cfg_i_offset(1,1);
    cfg_i_repeat(SIGNAL_LENGTH-FILTER_ORDER+1,0);  // 实际上这里就是不设 repeat-time 上限，符合滑窗的规则
    cfg_i_repeat(SIGNAL_LENGTH-FILTER_ORDER+1,1); 
    cfg_reuse(SIGNAL_LENGTH-FILTER_ORDER+1,0);  //N
    cfg_reuse(FILTER_ORDER,1);
    cfg_stride(4,0); 
    cfg_stride(4,1); //N*4
    cfg_tilestride(128,0); //byte = k*4
    cfg_tilestride(128,1); //byte = 4
    cfg_reuse_empty();
    cfg_axi_load((uint32_t)fir_coeffs,0); //这条指令必须在 配置stride指令之后
	cfg_axi_load((uint32_t)input,1);

    for (int i = FILTER_ORDER - 1; i < length; i++) {
        // 全部 FILTER_ORDER 个系数都用到
        output[i] = 0;
        for (int j = 0; j < FILTER_ORDER; j++) {
            output[i] += cal_stream_rd_mul(0,1);
            //output[i] += input[i-FILTER_ORDER + 1+j] * fir_coeffs[j];
        }
    }

    /* ========================================================
     * 第三段：排空期（结尾）
     * i = length ~ length + FILTER_ORDER - 2
     * 输入已经结束，补零流入，有效系数个数递减
     * 输出额外的 FILTER_ORDER-1 个拖尾点
     * ======================================================== */
    for (int i = 0; i < FILTER_ORDER - 1; i++) {

        // 补零流入（数据流已结束）
        for (int j = FILTER_ORDER - 1; j > 0; j--) {
            shift_reg[j] = shift_reg[j-1];
        }
        shift_reg[0] = 0;

        // 有效系数个数从 FILTER_ORDER-1 递减到 1
        output[length + i] = 0;
        for (int j = 1; j <= FILTER_ORDER - 1 - i; j++) {
            output[length + i] += shift_reg[j] * fir_coeffs[j];
        }
    }
}



