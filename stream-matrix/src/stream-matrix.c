static int cfg_i(int outerIter,int length,int fifo_id)
{
    int rs1 = (outerIter & 0xffff) | ((length & 0xffff) << 16);
    asm volatile (
       ".insn r 0x0b, 0, 0, x0, %0, %1"
             :
             :"r"(rs1),"r"(fifo_id)
     );
    return 0; 
}

